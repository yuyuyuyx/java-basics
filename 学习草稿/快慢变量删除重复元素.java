package 学习草稿;

public class 快慢变量删除重复元素 {
    public static void main(String[] args) {
        /*
         * 化方向（待办清单）
         * 【优化方向 1】：添加“空数组”和“单元素数组”的边界校验。
         * 
         * 现状：你现在的数组是 {1, 1, 2, 2, 3, 3, 3}，长度是 7。如果数组长度是 0（空数组），你的 fast = 1 以及
         * array[slow] 都会直接报错崩溃。
         * 
         * 所需知识点：array.length 判断、if 边界拦截。
         * 
         * 当前可行性：🟢 现在就能做。在 int slow = 0; 前面加一句 if (array.length == 0) return; 即可。
         * 
         * 【优化方向 2】：把去重逻辑提取成独立的方法（复习重构技巧）。
         * 
         * 现状：所有逻辑都在 main 方法里。
         * 
         * 所需知识点：public static int removeDuplicates(int[] nums)、返回值 return slow +
         * 1（返回新数组的有效长度）。
         * 
         * 当前可行性：🟢 现在就能做。这也是 LeetCode 官方题解要求的函数签名，非常适合练习。
         * 
         * 【优化方向 3】：拓展到“最多保留两个重复项”（升阶挑战）。
         * 
         * 场景：如果数组是 {1,1,1,2,2,3}，要求每个元素最多出现两次，结果为 {1,1,2,2,3}。这依然可以用快慢指针，只是判断条件要改成
         * nums[slow - 1] != nums[fast]。
         * 
         * 所需知识点：快慢指针变体、边界逻辑判断。
         * 
         * 当前可行性：🟡 稍加摸索能做。这是 LeetCode 80 题，适合巩固双指针思维。
         * 
         * 【优化方向 4】：从“原地修改”到“创建新数组”（空间换时间）。
         * 
         * 现状：你是原地修改数组（空间复杂度 O(1)），非常高效。
         * 
         * 所需知识点：new int[]、Arrays.copyOf、集合框架（Set）。
         * 
         * 当前可行性：🔴 需等学完第5章“集合框架”。到时候用 Set 一步到位，但空间消耗会变大（O(n)）。
         */
        int slow = 0;// 慢变量，默认在索引一的位置
        int fast = 1;// 快变量，默认在索引1的位置
        // 慢变量在后面，快变量在前面，如果二者的元素不同，就把快变量的给慢变量的
        // 因为慢变量是位置，快变量把自己找到的元素放在位置上
        // 针对递增数组
        int[] array = { 1, 1, 2, 2, 3, 3, 3 };
        while (fast < array.length) {
            if (array[slow] != array[fast]) {
                slow++;// 这里慢变量需要自增，不然位置就只有0一个，约等于循环
                // 让慢的先自增，当前的索引先用，下一个加过后的索引准备给下一行用
                array[slow] = array[fast];

            }
            fast++;
        }
        for (int i = 0; i <= slow; i++) {// 慢变量包含全部位置，所以循环范围就是这个
            System.out.print(array[i] + " ");// " "保证元素间有间隔，不拥挤

        }
        System.out.println();// 别忘换行
    }
}
